import fs from 'node:fs';
import vm from 'node:vm';
import {pathToFileURL} from 'node:url';
const root=process.env.DEFENSE_REVIEW_OUTPUT?pathToFileURL(process.env.DEFENSE_REVIEW_OUTPUT+'/'):new URL('../../output/defense-reuse-20261104/',import.meta.url);
const count=process.env.DEFENSE_REVIEW_STRICT==='1'?16:20;
const page=fs.readFileSync(new URL('review.html',root),'utf8');
const details=Array.from({length:count},()=>({open:false}));
let listener;
const button={textContent:'展开全部六袋对比',addEventListener(event,fn){if(event!=='click')throw Error(event);listener=fn;}};
const context={document:{getElementById(id){if(id!=='expand')throw Error(id);return button;},querySelectorAll(selector){if(selector!=='details')throw Error(selector);return details;}}};
const script=page.match(/<script>([\s\S]*?)<\/script>/)[1];
vm.runInNewContext(script,context);
listener.call(button);
if(!details.every(d=>d.open)||button.textContent!=='收起全部六袋对比')throw Error('expand failed');
listener.call(button);
if(!details.every(d=>!d.open)||button.textContent!=='展开全部六袋对比')throw Error('collapse failed');
details[4].open=true;listener.call(button);
if(!details.every(d=>d.open))throw Error('mixed state failed');
const report={passed:true,cards:(page.match(/<article /g)||[]).length,svgs:(page.match(/<svg /g)||[]).length,sections:(page.match(/<section>/g)||[]).length,handlerChecks:3,scope:'Actual inline event handler with offline DOM doubles; not browser layout or native accessibility.'};
if(report.cards!==count||report.svgs!==count||report.sections!==4)throw Error('structure');
fs.writeFileSync(new URL('page-check.json',root),JSON.stringify(report,null,2));console.log(report);
